import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageJson = JSON.parse(
  fs.readFileSync(path.join(repositoryRoot, 'package.json'), 'utf8')
);

const git = (args) =>
  execFileSync('git', args, { cwd: repositoryRoot, encoding: 'utf8' }).trim();
const shortCommit = git(['rev-parse', '--short', 'HEAD']);
const dirty = git(['status', '--porcelain', '--', '.', ':!js/build-version.js']).length > 0;
const version = `v${packageJson.version}-dev-${shortCommit}${dirty ? '-dirty' : ''}`;
const outputPath = path.join(repositoryRoot, 'js', 'build-version.js');

fs.writeFileSync(
  outputPath,
  `// Generated by npm run stamp-version. Do not edit manually.\nwindow.LISTEN1_BUILD_VERSION = '${version}';\n`,
  'utf8'
);
console.log(`Stamped ${version}`);
